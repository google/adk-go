package authhandler

// ConfigError reports an auth config that is invalid or names a scheme or
// credential ADK cannot use: the errors adk-python's CredentialManager raises
// as ValueError. Its text is the text of Err.
type ConfigError struct{ Err error }

func (e *ConfigError) Error() string { return e.Err.Error() }

func (e *ConfigError) Unwrap() error { return e.Err }

//go:build unix

package benchutil

import (
	"syscall"
	"time"
)

// CPUTime returns the user plus system CPU time the process has used, GC and
// every goroutine included. Wall time per turn hides how much of a turn is
// waiting for goroutine handoffs, and CPU time is what a server pays for.
func CPUTime() time.Duration {
	var ru syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &ru); err != nil {
		return 0
	}
	return time.Duration(ru.Utime.Nano() + ru.Stime.Nano())
}

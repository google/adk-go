func TestInMemoryService_AppendEvent_PreservesInputEventTempState(t *testing.T) {
	ctx := t.Context()
	service := session.InMemoryService()

	createResp, err := service.Create(ctx, &session.CreateRequest{
		AppName: "testapp",
		UserID:  "testuser",
	})
	if err != nil {
		t.Fatalf("Failed to create session: %v", err)
	}

	event := &session.Event{
		ID:        "event1",
		Timestamp: time.Now(),
		Actions: session.EventActions{
			StateDelta: map[string]any{
				"temp:k1": "v1",
				"sk":      "v2",
			},
		},
	}

	if err := service.AppendEvent(ctx, createResp.Session, event); err != nil {
		t.Fatalf("AppendEvent failed: %v", err)
	}

	// Verify that the input event pointer's StateDelta map was not mutated in place.
	if _, exists := event.Actions.StateDelta["temp:k1"]; !exists {
		t.Errorf("expected temp:k1 to be preserved on input event after AppendEvent, but it was removed: %v", event.Actions.StateDelta)
	}
	if event.Actions.StateDelta["sk"] != "v2" {
		t.Errorf("expected non-temp key sk to remain in input event, got: %v", event.Actions.StateDelta)
	}

	// Verify that the stored event in the session has temp keys stripped.
	var storedEvent *session.Event
	for ev := range createResp.Session.Events().All() {
		storedEvent = ev
	}
	if storedEvent == nil {
		t.Fatalf("expected stored event in session, got nil")
	}
	if _, exists := storedEvent.Actions.StateDelta["temp:k1"]; exists {
		t.Errorf("expected temp:k1 to be stripped from stored event, but it still exists: %v", storedEvent.Actions.StateDelta)
	}
	if storedEvent.Actions.StateDelta["sk"] != "v2" {
		t.Errorf("expected non-temp key sk on stored event, got: %v", storedEvent.Actions.StateDelta)
	}
}

// TestInMemoryService_AppendEvent_StripsTempKeysFromCanonicalRecord covers
// what TestInMemoryService_AppendEvent_PreservesInputEventTempState does not:
// Create() and AppendEvent() hand callers a session.Session distinct from the
// service's own canonical record, so re-reading temp: stripping through that
// same handle cannot catch a bug in how the canonical record is built. A fresh Get() call is
// required to observe what any other caller (e.g. a later turn, a different
// goroutine) actually sees.
func TestInMemoryService_AppendEvent_StripsTempKeysFromCanonicalRecord(t *testing.T) {
	ctx := t.Context()
	service := session.InMemoryService()

	createResp, err := service.Create(ctx, &session.CreateRequest{
		AppName: "testapp",
		UserID:  "testuser",
	})
	if err != nil {
		t.Fatalf("Failed to create session: %v", err)
	}

	event := &session.Event{
		ID:        "event1",
		Timestamp: time.Now(),
		Actions: session.EventActions{
			StateDelta: map[string]any{
				"temp:k1": "v1",
				"sk":      "v2",
			},
		},
	}
	if err := service.AppendEvent(ctx, createResp.Session, event); err != nil {
		t.Fatalf("AppendEvent failed: %v", err)
	}

	getResp, err := service.Get(ctx, &session.GetRequest{
		AppName:   "testapp",
		UserID:    "testuser",
		SessionID: createResp.Session.ID(),
	})
	if err != nil {
		t.Fatalf("Get failed: %v", err)
	}

	var storedEvent *session.Event
	for ev := range getResp.Session.Events().All() {
		storedEvent = ev
	}
	if storedEvent == nil {
		t.Fatalf("expected stored event in session, got nil")
	}
	if _, exists := storedEvent.Actions.StateDelta["temp:k1"]; exists {
		t.Errorf("temp:k1 leaked into the canonical record returned by Get(): %v", storedEvent.Actions.StateDelta)
	}
	if storedEvent.Actions.StateDelta["sk"] != "v2" {
		t.Errorf("expected non-temp key sk on stored event, got: %v", storedEvent.Actions.StateDelta)
	}
}

// TestInMemoryService_AppendEvent_MultipleEventsAllStripped guards against a
// narrower fix that only handles the first appended event: each event in a
// multi-turn session must independently have its temp: keys stripped from
// the canonical record.
func TestInMemoryService_AppendEvent_MultipleEventsAllStripped(t *testing.T) {
	ctx := t.Context()
	service := session.InMemoryService()

	createResp, err := service.Create(ctx, &session.CreateRequest{
		AppName: "testapp",
		UserID:  "testuser",
	})
	if err != nil {
		t.Fatalf("Failed to create session: %v", err)
	}

	for i, tempVal := range []string{"first", "second", "third"} {
		event := &session.Event{
			ID:        fmt.Sprintf("event%d", i),
			Timestamp: time.Now(),
			Actions: session.EventActions{
				StateDelta: map[string]any{
					"temp:turn": tempVal,
					"turn":      i,
				},
			},
		}
		if err := service.AppendEvent(ctx, createResp.Session, event); err != nil {
			t.Fatalf("AppendEvent(%d) failed: %v", i, err)
		}
	}

	getResp, err := service.Get(ctx, &session.GetRequest{
		AppName:   "testapp",
		UserID:    "testuser",
		SessionID: createResp.Session.ID(),
	})
	if err != nil {
		t.Fatalf("Get failed: %v", err)
	}

	i := 0
	for ev := range getResp.Session.Events().All() {
		if _, exists := ev.Actions.StateDelta["temp:turn"]; exists {
			t.Errorf("event %d: temp:turn leaked into the canonical record: %v", i, ev.Actions.StateDelta)
		}
		if ev.Actions.StateDelta["turn"] != i {
			t.Errorf("event %d: expected non-temp key turn=%d, got: %v", i, i, ev.Actions.StateDelta)
		}
		i++
	}
	if i != 3 {
		t.Fatalf("expected 3 stored events, got %d", i)
	}
}

// TestInMemoryService_AppendEvent_CopiesCompaction pins that a stored
// compaction cannot be edited through the pointer the caller passed in.
//
// Of every field on EventActions this is the one that must be copied: it names
// the range of history each future prompt drops, so a producer that kept its
// pointer could move the boundary after the append and silently change what
// the agent sees. The other three fields were already cloned.
func TestInMemoryService_AppendEvent_CopiesCompaction(t *testing.T) {
	ctx := t.Context()
	service := session.InMemoryService()

	createResp, err := service.Create(ctx, &session.CreateRequest{AppName: "app", UserID: "user"})
	if err != nil {
		t.Fatalf("Create: %v", err)
	}
	sess := createResp.Session

	start := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	end := start.Add(time.Minute)
	mine := &session.EventCompaction{
		StartTimestamp:   start,
		EndTimestamp:     end,
		CompactedContent: &genai.Content{Role: "model", Parts: []*genai.Part{{Text: "summary"}}},
	}
	event := &session.Event{ID: "c1", Author: "user"}
	event.Actions.Compaction = mine
	if err := service.AppendEvent(ctx, sess, event); err != nil {
		t.Fatalf("AppendEvent: %v", err)
	}

	// Rewrite the record through the pointer we still hold. A stored event must
	// not follow.
	mine.EndTimestamp = end.Add(100 * time.Hour)
	mine.CompactedContent.Parts[0].Text = "rewritten after the append"

	got, err := service.Get(ctx, &session.GetRequest{AppName: "app", UserID: "user", SessionID: sess.ID()})
	if err != nil {
		t.Fatalf("Get: %v", err)
	}
	stored := got.Session.Events().At(0).Actions.Compaction
	if stored == nil {
		t.Fatal("compaction was not persisted")
	}
	if !stored.EndTimestamp.Equal(end) {
		t.Errorf("stored EndTimestamp = %v, want %v: the caller moved the covered range after the append", stored.EndTimestamp, end)
	}
	if txt := stored.CompactedContent.Parts[0].Text; txt != "summary" {
		t.Errorf("stored summary = %q, want %q: the caller rewrote the stored content", txt, "summary")
	}
}

// TestInMemoryService_AppendEventClonesSetModelResponse pins that the stored

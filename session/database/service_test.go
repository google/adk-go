func emptyServiceFromDB(t *testing.T) *databaseService {
	t.Helper()
	db, err := gorm.Open(sqlite.Open("file::memory:?cache=shared"), &gorm.Config{PrepareStmt: true})
	if err != nil {
		t.Fatalf("failed to open db: %v", err)
	}
	svc, err := NewSessionServiceFromDB(db)
	if err != nil {
		t.Fatalf("NewSessionServiceFromDB() failed: %v", err)
	}
	if err := AutoMigrate(svc); err != nil {
		t.Fatalf("AutoMigrate failed: %v", err)
	}
	dbSvc := svc.(*databaseService)
	t.Cleanup(func() {
		modelsToDelete := []any{&storageEvent{}, &storageSession{}, &storageUserState{}, &storageAppState{}}
		for _, model := range modelsToDelete {
			stmt := &gorm.Statement{DB: dbSvc.db}
			if err := stmt.Parse(model); err != nil {
				t.Errorf("failed to parse model: %v", err)
				continue
			}
			if err := dbSvc.db.Exec(`DELETE FROM ` + stmt.Table + ` WHERE true`).Error; err != nil {
				t.Errorf("failed to delete from %s: %v", stmt.Table, err)
			}
		}
		sqlDB, err := dbSvc.db.DB()
		if err != nil {
			t.Errorf("failed to get *sql.DB: %v", err)
			return
		}
		if err := sqlDB.Close(); err != nil {
			t.Errorf("failed to close *sql.DB: %v", err)
		}
	})
	return dbSvc
}

func emptyService(t *testing.T) *databaseService {
	t.Helper()
	gormConfig := &gorm.Config{
		PrepareStmt: true,
	}

	service, err := NewSessionService(sqlite.Open("file::memory:?cache=shared"), gormConfig)
	if err != nil {
		t.Fatalf("Failed to create session service: %v", err)
	}
	dbservice, ok := service.(*databaseService)
	if !ok {
		t.Fatalf("invalid session service type")
	}

	err = AutoMigrate(service)
	if err != nil {
		t.Fatalf("Failed to AutoMigrate db: %v", err)
	}

	t.Cleanup(func() {
		t.Log("CLEANUP: Deleting all rows from tables...")

		// Define models in Child-to-Parent order
		modelsToDelete := []any{
			&storageEvent{}, // Child-most
			&storageSession{},
			&storageUserState{},
			&storageAppState{}, // Parent-most
		}

		for _, model := range modelsToDelete {
			// GORM statement parser to get table names
			stmt := &gorm.Statement{DB: dbservice.db}
			// Parse the model to get its table name
			if err := stmt.Parse(model); err != nil {
				t.Errorf("Failed to parse model schema for cleanup: %v", err)
				continue
			}
			tableName := stmt.Table

			// Exec with "WHERE true" instead of gorm.Delete()
			// satisfies Spanner's requirement for a WHERE clause.
			if err := dbservice.db.Exec(`DELETE FROM ` + tableName + ` WHERE true`).Error; err != nil {
				t.Errorf("Failed to delete from table %s: %v", tableName, err)
			}
		}
		sqlDB, err := dbservice.db.DB()
		if err != nil {
			t.Errorf("Failed to get underlying *sql.DB: %v", err)
			return
		}
		if err := sqlDB.Close(); err != nil {
			t.Errorf("Failed to close database connection: %v", err)
		}
	})

	return dbservice
}

func TestDatabaseService_AppendEvent_PreservesInputEventTempState(t *testing.T) {
	ctx := t.Context()
	s := emptyService(t)

	createResp, err := s.Create(ctx, &session.CreateRequest{
		AppName: "testapp",
		UserID:  "testuser",
	})
	if err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	event := &session.Event{
		ID:        "event1",
		Timestamp: time.Now(),
		Actions: session.EventActions{
			StateDelta: map[string]any{
				"temp:k1": "v1",
				"sk":      "v2",
			},
		},
	}

	if err := s.AppendEvent(ctx, createResp.Session, event); err != nil {
		t.Fatalf("AppendEvent failed: %v", err)
	}

	// Verify that the input event pointer's StateDelta map was not mutated in place.
	if _, exists := event.Actions.StateDelta["temp:k1"]; !exists {
		t.Errorf("expected temp:k1 to be preserved on input event after AppendEvent, but it was removed: %v", event.Actions.StateDelta)
	}
	if event.Actions.StateDelta["sk"] != "v2" {
		t.Errorf("expected non-temp key sk to remain in input event, got: %v", event.Actions.StateDelta)
	}

	// Verify that the stored event in the session has temp keys stripped.
	var storedEvent *session.Event
	for ev := range createResp.Session.Events().All() {
		storedEvent = ev
	}
	if storedEvent == nil {
		t.Fatalf("expected stored event in session, got nil")
	}
	if _, exists := storedEvent.Actions.StateDelta["temp:k1"]; exists {
		t.Errorf("expected temp:k1 to be stripped from stored event, but it still exists: %v", storedEvent.Actions.StateDelta)
	}
	if storedEvent.Actions.StateDelta["sk"] != "v2" {
		t.Errorf("expected non-temp key sk on stored event, got: %v", storedEvent.Actions.StateDelta)
	}
}

func TestDatabaseService_AppendEvent_FailurePreservesSession(t *testing.T) {
	for _, failure := range []string{"canceled", "insert", "commit", "stale", "deleted"} {
		t.Run(failure, func(t *testing.T) {
			s := emptyService(t)
			start := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
			ctx := platform.WithTimeProvider(t.Context(), func() time.Time { return start })
			created, err := s.Create(ctx, &session.CreateRequest{
				AppName: "app", UserID: "user",
				State: map[string]any{"key": "before", "app:key": "before", "user:key": "before"},
			})
			if err != nil {
				t.Fatal(err)
			}
			sess := created.Session
			accepted := &session.Event{ID: "accepted", Timestamp: start.Add(time.Second)}
			if err := s.AppendEvent(ctx, sess, accepted); err != nil {
				t.Fatal(err)
			}
			wantTime := sess.LastUpdateTime()
			wantState := maps.Collect(sess.State().All())
			// Temporary state remains local even on failure, matching adk-python.
			wantState["temp:scratch"] = "local"
			event := &session.Event{
				ID: "rejected", Timestamp: start.Add(3 * time.Second),
				Actions: session.EventActions{StateDelta: map[string]any{
					"key": "after", "new": true, "app:key": "after", "user:key": "after", "temp:scratch": "local",
				}},
			}
			read := func() session.Session {
				t.Helper()
				got, err := s.Get(t.Context(), &session.GetRequest{AppName: "app", UserID: "user", SessionID: sess.ID()})
				if err != nil {
					t.Fatal(err)
				}
				return got.Session
			}
			var wantErr error
			switch failure {
			case "canceled":
				var cancel context.CancelFunc
				ctx, cancel = context.WithCancel(ctx)
				cancel()
				wantErr = context.Canceled
			case "insert":
				wantErr = errors.New("injected append failure")
				callback := s.db.Callback().Create()
				if err := callback.Before("*").Register("test:fail_append", func(tx *gorm.DB) {
					if tx.Statement.Table == "events" {
						_ = tx.AddError(wantErr)
					}
				}); err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() { _ = callback.Remove("test:fail_append") })
			case "commit":
				wantErr = errors.New("injected commit failure")
				db, err := s.db.DB()
				if err != nil {
					t.Fatal(err)
				}
				pool := s.db.Statement.ConnPool
				s.db.Statement.ConnPool = appendTestPool{DB: db, commit: func(*sql.Tx) error { return wantErr }}
				t.Cleanup(func() { s.db.Statement.ConnPool = pool })
			case "stale":
				if err := s.AppendEvent(ctx, read(), &session.Event{ID: "newer", Timestamp: start.Add(2 * time.Second)}); err != nil {
					t.Fatal(err)
				}
			case "deleted":
				if err := s.Delete(ctx, &session.DeleteRequest{AppName: "app", UserID: "user", SessionID: sess.ID()}); err != nil {
					t.Fatal(err)
				}
				wantErr = session.ErrNotFound
			}
			var before session.Session
			if failure != "deleted" {
				before = read()
			}
			err = s.AppendEvent(ctx, sess, event)
			if err == nil || (wantErr != nil && !errors.Is(err, wantErr)) {
				t.Fatalf("AppendEvent did not preserve the failure: %v", err)
			}
			if sess.Events().Len() != 1 || sess.Events().At(0) != accepted {
				t.Error("failed append changed local history")
			}
			if !cmp.Equal(wantState, maps.Collect(sess.State().All())) {
				t.Error("failed append changed persistent local state or lost temporary state")
			}
			if !sess.LastUpdateTime().Equal(wantTime) {
				t.Error("failed append changed the local update time")
			}
			if failure == "deleted" {
				_, err := s.Get(t.Context(), &session.GetRequest{AppName: "app", UserID: "user", SessionID: sess.ID()})
				if !errors.Is(err, session.ErrNotFound) {
					t.Fatalf("Get after failed append did not preserve deletion: %v", err)
				}
				return
			}
			after := read()
			if after.Events().Len() != before.Events().Len() ||
				!cmp.Equal(maps.Collect(before.State().All()), maps.Collect(after.State().All())) ||
				!after.LastUpdateTime().Equal(before.LastUpdateTime()) {
				t.Error("failed append changed the stored session")
			}
			if failure == "canceled" {
				if err := s.AppendEvent(t.Context(), sess, event); err != nil {
					t.Fatal(err)
				}
				stored := read()
				state := maps.Collect(sess.State().All())
				delete(state, "temp:scratch")
				if sess.Events().Len() != 2 || stored.Events().Len() != 2 || sess.Events().At(1).ID != event.ID {
					t.Error("retry left failed or duplicate events in local history")
				}
				if !cmp.Equal(state, maps.Collect(stored.State().All())) || !sess.LastUpdateTime().Equal(stored.LastUpdateTime()) {
					t.Error("local session differs from storage after a successful retry")
				}
			}
		})
	}
}

// appendTestPool lets tests fail or pause Commit while executing real SQL.
type appendTestPool struct {
	*sql.DB
	commit func(*sql.Tx) error
}

func (p appendTestPool) BeginTx(ctx context.Context, opts *sql.TxOptions) (gorm.ConnPool, error) {
	tx, err := p.DB.BeginTx(ctx, opts)
	if err != nil {
		return nil, err
	}
	return &appendTestTx{Tx: tx, commit: p.commit}, nil
}

type appendTestTx struct {
	*sql.Tx
	commit func(*sql.Tx) error
}

func (tx appendTestTx) Commit() error { return tx.commit(tx.Tx) }

func TestDatabaseService_AppendEvent_CommitOrder(t *testing.T) {
	s := emptyService(t)
	created, err := s.Create(t.Context(), &session.CreateRequest{AppName: "app", UserID: "user"})
	if err != nil {
		t.Fatal(err)
	}
	sess := created.Session
	timestamp := sess.LastUpdateTime().Add(time.Second)
	db, err := s.db.DB()
	if err != nil {
		t.Fatal(err)
	}
	db.SetMaxOpenConns(1)
	committed := make(chan struct{})
	release := make(chan struct{})
	var releaseOnce sync.Once
	unblock := func() { releaseOnce.Do(func() { close(release) }) }
	defer unblock()
	pool := s.db.Statement.ConnPool
	var commits int
	s.db.Statement.ConnPool = appendTestPool{DB: db, commit: func(tx *sql.Tx) error {
		if err := tx.Commit(); err != nil {
			return err
		}
		commits++
		if commits == 1 {
			close(committed)
			<-release
		}
		return nil
	}}
	t.Cleanup(func() { s.db.Statement.ConnPool = pool })
	appendEvent := func(id string) error {
		delta := map[string]any{"last": id}
		if id == "first" {
			delta["temp:scratch"] = "first"
		}
		return s.AppendEvent(t.Context(), sess, &session.Event{
			ID: id, Timestamp: timestamp,
			Actions: session.EventActions{StateDelta: delta},
		})
	}
	firstDone := make(chan error, 1)
	go func() { firstDone <- appendEvent("first") }()
	select {
	case <-committed:
	case err := <-firstDone:
		t.Fatalf("first append returned before Commit: %v", err)
	}
	if err := sess.State().Set("temp:scratch", "newer"); err != nil {
		t.Fatal(err)
	}
	// A queued append must observe its deadline while the first Commit waits.
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Millisecond)
	defer cancel()
	canceledDone := make(chan error, 1)
	go func() {
		canceledDone <- s.AppendEvent(ctx, sess, &session.Event{ID: "canceled", Timestamp: timestamp})
	}()
	<-ctx.Done()
	select {
	case err := <-canceledDone:
		if !errors.Is(err, context.DeadlineExceeded) {
			t.Fatalf("queued append did not return its deadline error: %v", err)
		}
	case <-time.After(5 * time.Second):
		unblock()
		if err := <-canceledDone; !errors.Is(err, context.DeadlineExceeded) {
			t.Errorf("queued append returned an unexpected error: %v", err)
		}
		if err := <-firstDone; err != nil {
			t.Error(err)
		}
		t.Fatal("queued append waited for another append after its deadline")
	}
	// The first event is committed, but its local update is still pending.
	// Another append must wait so it cannot publish ahead of the first.
	secondStarted := make(chan struct{})
	secondDone := make(chan struct{})
	var secondErr error
	go func() {
		close(secondStarted)
		secondErr = appendEvent("second")
		close(secondDone)
	}()
	<-secondStarted
	select {
	case <-secondDone:
		t.Error("second append finished before the first local update")
	case <-time.After(100 * time.Millisecond):
	}
	unblock()
	// Read concurrently with publication to exercise timestamp synchronization.
	for firstDone != nil || secondDone != nil {
		select {
		case err := <-firstDone:
			firstDone = nil
			if err != nil {
				t.Error(err)
			}
		case <-secondDone:
			secondDone = nil
			if secondErr != nil {
				t.Error(secondErr)
			}
		default:
			sess.LastUpdateTime()
		}
	}
	if sess.Events().Len() != 2 || sess.Events().At(0).ID != "first" || sess.Events().At(1).ID != "second" {
		t.Error("local history does not follow database commit order")
	}
	last, err := sess.State().Get("last")
	if err != nil || last != "second" {
		t.Error("local state does not follow database commit order")
	}
	if value, err := sess.State().Get("temp:scratch"); err != nil || value != "newer" {
		t.Error("committing an event reapplied its temporary state")
	}
}

// TestEventsSharingATimestampComeBackInAStableOrder pins that a tie does not
// flip between reads.
//
// Timestamps are truncated to microseconds on write, so two events in one tick
// are ordinary. The query fetches DESC so a limit takes the most recent and
// then reverses, and without a tiebreak SQLite's stable sort hands ties back in
// reverse insertion order, differently from how they went in. Compaction reads
// this order to decide what a summary stands for, so a pair that swaps lets a
// record cover an event nothing summarized.
func TestEventsSharingATimestampComeBackInAStableOrder(t *testing.T) {
	// Not parallel: emptyService opens file::memory:?cache=shared, so every
	// test in this package works against one database.

	ctx := context.Background()
	svc := emptyService(t)
	const appName, userID = "app", "user"
	created, err := svc.Create(ctx, &session.CreateRequest{AppName: appName, UserID: userID})
	if err != nil {
		t.Fatalf("Create() error = %v", err)
	}
	sess := created.Session

	// Six events on one instant, appended in a known order. The ids ascend
	// because the query breaks ties on id: random ids land in exact reverse
	// insertion order once in 720 runs and fail the check below.
	ts := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	var want []string
	for i := range 6 {
		ev := session.NewEvent(ctx, "inv1")
		ev.ID = fmt.Sprintf("event-%d", i)
		ev.Author = "author"
		ev.Timestamp = ts
		ev.LLMResponse.Content = genai.NewContentFromText(fmt.Sprintf("event %d", i), genai.RoleUser)
		if err := svc.AppendEvent(ctx, sess, ev); err != nil {
			t.Fatalf("AppendEvent() error = %v", err)
		}
		want = append(want, ev.ID)
	}

	read := func() []string {
		got, err := svc.Get(ctx, &session.GetRequest{AppName: appName, UserID: userID, SessionID: sess.ID()})
		if err != nil {
			t.Fatalf("Get() error = %v", err)
		}
		var ids []string
		for ev := range got.Session.Events().All() {
			ids = append(ids, ev.ID)
		}
		return ids
	}

	first := read()
	// Stable across reads is the property compaction depends on.
	for range 5 {
		if diff := cmp.Diff(first, read()); diff != "" {
			t.Fatalf("the order of tied events changed between reads (-first +later):\n%s", diff)
		}
	}
	// And not the reverse of how they were appended, which is what the missing
	// tiebreak produced.
	reversed := slices.Clone(want)
	slices.Reverse(reversed)
	if cmp.Diff(reversed, first) == "" {
		t.Errorf("tied events came back in reverse insertion order:\n%v", first)
	}
}

